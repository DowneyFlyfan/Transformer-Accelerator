#!/usr/bin/env python3
"""Generate synthesizable LUT include files for softmax.

Usage:
    python gen_luts.py [--lut_aw 5] [--exp_bw 16] [--in_bw 8] [--out_dir .]

Generates:
    exp_lut.svh   — case-based ROM for 2^(i/LutSize)
    recip_lut.svh — case-based ROM for 1/x, x in [0.5,1.0)
"""

import argparse
from pathlib import Path


def gen_exp_lut(lut_aw: int, exp_bw: int) -> list[int]:
    lut_size = 1 << lut_aw
    lut = []
    for i in range(lut_size):
        val = int(2.0 ** (i / lut_size) * (1 << (exp_bw - 2)))
        lut.append(val & ((1 << exp_bw) - 1))
    return lut


def gen_recip_lut(lut_aw: int, exp_bw: int) -> list[int]:
    lut_size = 1 << lut_aw
    lut = []
    for i in range(lut_size):
        val = int((1.0 / (0.5 + i / (2 * lut_size))) * (1 << (exp_bw - 3)))
        lut.append(val & ((1 << exp_bw) - 1))
    return lut


def write_case_rom(path: Path, values: list[int], addr_bw: int, data_bw: int,
                   func_name: str):
    """Generate a case-based ROM as a combinational function in .svh."""
    hex_w = (data_bw + 3) // 4
    addr_hex_w = (addr_bw + 3) // 4
    with open(path, "w") as f:
        f.write(f"// Auto-generated by gen_luts.py — do not edit\n")
        f.write(f"// {func_name}: {len(values)} entries, "
                f"{addr_bw}-bit addr, {data_bw}-bit data\n")
        f.write(f"function automatic [{data_bw-1}:0] "
                f"{func_name};\n")
        f.write(f"  input [{addr_bw-1}:0] addr;\n")
        f.write(f"  case (addr)\n")
        for i, v in enumerate(values):
            f.write(f"    {addr_bw}'h{i:0{addr_hex_w}x}: "
                    f"{func_name} = {data_bw}'h{v:0{hex_w}x};\n")
        f.write(f"    default: {func_name} = '0;\n")
        f.write(f"  endcase\n")
        f.write(f"endfunction\n")


def main():
    parser = argparse.ArgumentParser(
        description="Generate softmax LUT .svh files")
    parser.add_argument("--lut_aw", type=int, default=5)
    parser.add_argument("--exp_bw", type=int, default=16)
    parser.add_argument("--in_bw", type=int, default=8)
    parser.add_argument("--out_dir", type=str, default=".")
    args = parser.parse_args()

    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    exp_lut = gen_exp_lut(args.lut_aw, args.exp_bw)
    recip_lut = gen_recip_lut(args.lut_aw, args.exp_bw)

    write_case_rom(out / "exp_lut.svh", exp_lut,
                   args.lut_aw, args.exp_bw, "exp_lut_rom")
    write_case_rom(out / "recip_lut.svh", recip_lut,
                   args.lut_aw, args.exp_bw, "recip_lut_rom")

    # LOG2E for verification
    scale_bw = args.in_bw - 2
    log2e = int(1.4427 * (1 << scale_bw))
    print(f"LUT_AW={args.lut_aw}, EXP_BW={args.exp_bw}, "
          f"IN_BW={args.in_bw}")
    print(f"LOG2E (ScaleBW={scale_bw}): {log2e} (0x{log2e:x})")
    print(f"Generated -> {out / 'exp_lut.svh'}")
    print(f"Generated -> {out / 'recip_lut.svh'}")


if __name__ == "__main__":
    main()
