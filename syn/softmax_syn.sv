// Softmax via base-2 conversion + small LUT
// Pipeline: max_tree -> sub -> x log2e -> LUT+shift -> sum -> recip_LUT -> norm
// Synthesis-friendly: LUTs loaded via $readmemh
module softmax #(
    parameter int N      = 8,   // Number of input elements
    parameter int IN_BW  = 8,   // Signed integer input bit width
    // NOTE: LUT_AW is input resolution (step size)
    // EXP_BW is output resolution (Quantization Accuracy)
    parameter int LUT_AW = 5,   // LUT address width (2^5 = 32 entries),
    parameter int EXP_BW = 16,  // Internal exp value bit width
    parameter int OUT_BW = 16   // Output Q0.OUT_BW unsigned
) (
    input  logic                     clk,
    input  logic                     rst_n,
    input  logic                     valid_in,
    input  logic signed [ IN_BW-1:0] in       [N],
    output logic        [OUT_BW-1:0] out      [N],
    output logic                     valid_out
);

  // ================ Constants ================
  localparam int MaxStage = $clog2(N);
  localparam int MultDelay1 = $clog2(IN_BW) + 1;
  localparam int MultDelay2 = $clog2(EXP_BW) + 1;
  localparam int LutSize = 1 << LUT_AW;
  localparam int SumBW = EXP_BW + MaxStage;
  localparam int MsbBW = $clog2(SumBW);
  localparam int TotalDelay =
      2 * MaxStage + MultDelay1 + MultDelay2 + 11;

  // log2(e) ~ 1.4427 in signed Q2.(IN_BW-2)
  //   1 sign bit + 1 integer bit + (IN_BW-2) fractional bits
  localparam int ScaleBW = IN_BW - 2;
  localparam logic signed [IN_BW-1:0] LOG2E =
      IN_BW'(14427 * (1 << ScaleBW) / 10000);

  // ================ LUTs (case-ROM via include) ================
  // Generated by gen_luts.py — run before synthesis:
  //   python gen_luts.py --lut_aw <LUT_AW> --exp_bw <EXP_BW>

  `include "exp_lut.svh"
  `include "recip_lut.svh"

  // ========================================================
  // P1: Max Comparator Tree  (MaxStage cycles)
  // ========================================================
  logic signed [IN_BW-1:0] cmp [MaxStage+1][N];
  logic signed [IN_BW-1:0] in_d[  MaxStage][N];

  always_comb begin
    for (int i = 0; i < N; i++) cmp[0][i] = in[i];
  end

  always_ff @(posedge clk) begin
    // Comparator tree: keep the larger of each pair
    for (int s = 0; s < MaxStage; s++)
    for (int i = 0; i < (N >> (s + 1)); i++)
    cmp[s+1][i] <=
        (cmp[s][2*i] > cmp[s][2*i+1])
        ? cmp[s][2*i] : cmp[s][2*i+1];
    // Delay raw inputs to align with max output
    for (int i = 0; i < N; i++) in_d[0][i] <= in[i];
    for (int s = 1; s < MaxStage; s++)
    for (int i = 0; i < N; i++)
      in_d[s][i] <= in_d[s-1][i];
  end

  // ========================================================
  // P2: Subtract Max  (1 cycle)
  //   diff[i] = x[i] - max  in (-inf, 0]
  // ========================================================
  logic signed [IN_BW-1:0] diff[N];

  always_ff @(posedge clk)
    for (int i = 0; i < N; i++)
      diff[i] <= in_d[MaxStage-1][i] - cmp[MaxStage][0];

  // ========================================================
  // P3: Multiply by log2(e) via int_multiplier
  //   y = (x-max) * log2(e)        (MultDelay1 cycles)
  // ========================================================
  logic [2*IN_BW-1:0] y_raw[N];

  for (genvar i = 0; i < N; i++) begin : g_log2e
    int_multiplier #(
        .BW(IN_BW)
    ) u_log2e (
        .clk(clk),
        .in1(diff[i]),
        .in2(LOG2E),
        .out(y_raw[i])
    );
  end

  // ========================================================
  // P4: Split into integer + fraction  (1 cycle)
  // ========================================================
  logic signed [ IN_BW-1:0] y_int [N];
  logic        [LUT_AW-1:0] y_frac[N];

  always_ff @(posedge clk)
    for (int i = 0; i < N; i++) begin
      y_int[i]  <=
          IN_BW'($signed(y_raw[i]) >>> ScaleBW);
      y_frac[i] <= y_raw[i][(ScaleBW-1)-:LUT_AW];
    end

  // ========================================================
  // P5a: LUT lookup for 2^frac  (1 cycle)
  // ========================================================
  logic [EXP_BW-1:0] exp_frac[N];
  logic signed [IN_BW-1:0] y_int_d[N];

  always_ff @(posedge clk)
    for (int i = 0; i < N; i++) begin
      exp_frac[i] <= exp_lut_rom(y_frac[i]);
      y_int_d[i]  <= y_int[i];
    end

  // ========================================================
  // P5b: Barrel shift by y_int  (1 cycle)
  // ========================================================
  logic [EXP_BW-1:0] ev[N];

  always_ff @(posedge clk)
    for (int i = 0; i < N; i++)
      ev[i] <=
          (y_int_d[i] < -(EXP_BW - 1))
          ? '0
          : exp_frac[i] >> ($unsigned(-y_int_d[i]));

  // ========================================================
  // P6: Sum all exp values via adder_tree  (MaxStage cycles)
  // ========================================================
  logic signed [EXP_BW-1:0] ev_signed[N];
  logic signed [ SumBW-1:0] esum;

  always_comb
    for (int i = 0; i < N; i++)
      ev_signed[i] = $signed(ev[i]);

  adder_tree #(
      .BW (EXP_BW),
      .NUM(N)
  ) u_sum (
      .clk(clk),
      .in (ev_signed),
      .out(esum)
  );

  // Delay ev[] by MaxStage+2 cycles to match sum + P7a/P7b latency
  logic [EXP_BW-1:0] ev_pipe[MaxStage+2][N];

  always_ff @(posedge clk) begin
    for (int i = 0; i < N; i++)
      ev_pipe[0][i] <= ev[i];
    for (int s = 1; s <= MaxStage + 1; s++)
    for (int i = 0; i < N; i++)
      ev_pipe[s][i] <= ev_pipe[s-1][i];
  end

  // ========================================================
  // P7a: Priority encoder  (1 cycle)
  // ========================================================
  logic [MsbBW-1:0] msb_pos;

  always_comb begin
    msb_pos = '0;
    for (int i = 0; i < SumBW; i++)
      if (esum[i]) msb_pos = MsbBW'(i);
  end

  logic [MsbBW-1:0] msb_pos_r;
  logic [SumBW-1:0] esum_r;

  always_ff @(posedge clk) begin
    msb_pos_r <= msb_pos;
    esum_r    <= esum;
  end

  // ========================================================
  // P7b: Normalize + extract LUT index  (1 cycle)
  // ========================================================
  logic [ SumBW-1:0] snorm;
  logic [LUT_AW-1:0] ridx;

  always_comb begin
    snorm = esum_r << (SumBW - 1 - msb_pos_r);
    ridx  = snorm[SumBW-2-:LUT_AW];
  end

  logic [LUT_AW-1:0] ridx_r;
  logic [ MsbBW-1:0] msb_pos_r2;

  always_ff @(posedge clk) begin
    ridx_r     <= ridx;
    msb_pos_r2 <= msb_pos_r;
  end

  // ========================================================
  // P7c: Recip LUT lookup  (1 cycle)
  // ========================================================
  logic [EXP_BW-1:0] rval;
  logic [ MsbBW-1:0] rshift;
  logic [EXP_BW-1:0] ev_aligned[N];

  always_ff @(posedge clk) begin
    rval   <= recip_lut_rom(ridx_r);
    rshift <= msb_pos_r2;
    for (int i = 0; i < N; i++)
      ev_aligned[i] <= ev_pipe[MaxStage+1][i];
  end

  // ========================================================
  // P8: Normalize  exp[i] x (1/sum)  via int_multiplier
  //   (MultDelay2 cycles)
  // ========================================================
  logic signed [EXP_BW-1:0] ev_s2[N];
  logic signed [EXP_BW-1:0] rv_s;

  always_comb begin
    for (int i = 0; i < N; i++)
      ev_s2[i] =
          $signed({1'b0, ev_aligned[i][EXP_BW-2:0]});
    rv_s = $signed({1'b0, rval[EXP_BW-2:0]});
  end

  logic [2*EXP_BW-1:0] prod[N];

  for (genvar i = 0; i < N; i++) begin : g_norm
    int_multiplier #(
        .BW(EXP_BW)
    ) u_norm (
        .clk(clk),
        .in1(ev_s2[i]),
        .in2(rv_s),
        .out(prod[i])
    );
  end

  // Pipeline rshift through multiplier latency
  logic [MsbBW-1:0] rs_pipe[MultDelay2];

  always_ff @(posedge clk) begin
    rs_pipe[0] <= rshift;
    for (int s = 1; s < MultDelay2; s++)
      rs_pipe[s] <= rs_pipe[s-1];
  end

  // ========================================================
  // P9a: Compute shift amount + abs + register prod  (1 cycle)
  // ========================================================
  localparam int ShiftBW =
      (2 * EXP_BW > OUT_BW)
      ? 2 * EXP_BW : OUT_BW + 1;
  localparam int ShAmtBW = $clog2(ShiftBW) + 1;

  logic [ShAmtBW-1:0] abs_sh_r[N];
  logic               sh_dir_r[N];  // 0=right, 1=left
  logic [2*EXP_BW-1:0] prod_r[N];

  always_ff @(posedge clk)
    for (int i = 0; i < N; i++) begin
      logic signed [ShAmtBW-1:0] sh_amt;
      sh_amt = ShAmtBW'(
          $signed({1'b0, rs_pipe[MultDelay2-1]})
          + (EXP_BW - 2 - OUT_BW));
      abs_sh_r[i] <= (sh_amt >= 0)
          ? ShAmtBW'(sh_amt)
          : ShAmtBW'(-sh_amt);
      sh_dir_r[i] <= (sh_amt < 0);
      prod_r[i]   <= prod[i];
    end

  // ========================================================
  // P9b: Coarse shift (upper bits of abs_sh_r)  (1 cycle)
  // ========================================================
  logic [ShiftBW-1:0] coarse_r[N];
  logic         [2:0] fine_r[N];

  always_ff @(posedge clk)
    for (int i = 0; i < N; i++) begin
      if (sh_dir_r[i])
        coarse_r[i] <=
            ShiftBW'(prod_r[i])
            << {abs_sh_r[i][ShAmtBW-1:3], 3'b0};
      else
        coarse_r[i] <=
            ShiftBW'(prod_r[i])
            >> {abs_sh_r[i][ShAmtBW-1:3], 3'b0};
      fine_r[i] <= abs_sh_r[i][2:0];
    end

  // ========================================================
  // P9c: Fine shift (lower 3 bits)  (1 cycle)
  // ========================================================
  logic [ShiftBW-1:0] shifted_r[N];

  always_ff @(posedge clk)
    for (int i = 0; i < N; i++)
      shifted_r[i] <= coarse_r[i] >> fine_r[i];

  // ========================================================
  // P9d: Saturate -> Q0.OUT_BW output  (1 cycle)
  // ========================================================
  always_ff @(posedge clk)
    for (int i = 0; i < N; i++)
      if (|shifted_r[i][ShiftBW-1:OUT_BW])
        out[i] <= {OUT_BW{1'b1}};
      else
        out[i] <= shifted_r[i][OUT_BW-1:0];

  // ========================================================
  // Valid shift register
  // ========================================================
  logic [TotalDelay-1:0] vsr;

  always_ff @(posedge clk or negedge rst_n)
    if (!rst_n) vsr <= '0;
    else vsr <= {vsr[TotalDelay-2:0], valid_in};

  always_comb valid_out = vsr[TotalDelay-1];

endmodule
